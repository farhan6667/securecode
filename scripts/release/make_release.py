#!/usr/bin/env python3
"""Build and sign a release zip for the auto-updater (run by the security team only).

    py -I scripts/release/make_release.py --version <X.Y.Z> --key C:\\secure\\org-appsec-release

    py -I scripts/release/make_release.py --manifest     # rewrite the "## Files" list at the end of MANIFEST.txt

Writes dist/<asset> and dist/<asset>.sig. Publishing is a separate, deliberate step:
    gh release create v<X.Y.Z> dist/<asset> dist/<asset>.sig --repo <org>/<repo> --notes-file <release notes for X.Y.Z>
The private key must stay offline or on the release officer's machine (never in the repo, never in CI).
"""
import argparse, json, re, shutil, subprocess, sys, zipfile
from pathlib import Path

PKG = Path(__file__).resolve().parents[2]
EXCLUDE_DIRS = {".git", ".security", "__pycache__", "dist", ".pytest_cache", "node_modules", ".ai-media", "org-internal",
                ".venv", "venv"}


def release_files():
    """Only files committed to git go into a public release (drafts, local images and notes never do).
    Without a git checkout, fall back to the folder walk with EXCLUDE_DIRS."""
    if (PKG / ".git").exists():
        git = shutil.which("git") or sys.exit("git not found; build releases from a git checkout")
        # The zip takes the files from disk, so the tree must match the last commit exactly.
        dirty = subprocess.run([git, "-C", str(PKG), "status", "--porcelain", "--untracked-files=no"],
                               capture_output=True, text=True, check=True).stdout.strip()
        if dirty:
            sys.exit("uncommitted changes in tracked files; commit or stash them so the release matches a commit:\n" + dirty[:2000])
        files = tracked_files(git)
        if not files:
            sys.exit("no committed files; make the first commit before building a release")
        return files
    return sorted(PKG.rglob("*"))


def tracked_files(git=None):
    """Every file git tracks, as absolute paths (no dirty check; release_files adds that)."""
    git = git or shutil.which("git") or sys.exit("git not found")
    out = subprocess.run([git, "-C", str(PKG), "ls-files", "-z"], capture_output=True, check=True).stdout
    return [PKG / p for p in out.decode("utf-8").split("\0") if p]


EXCLUDE_SUFFIX = (".pyc", ".sig", ".key", ".pem")
MANIFEST_FILES = "## Files"


def ships(f: Path) -> bool:
    """The one filter for what goes into the zip (also used for the MANIFEST.txt file list)."""
    rel = f.relative_to(PKG)
    return not (f.is_dir() or set(rel.parts) & EXCLUDE_DIRS or f.name.endswith(EXCLUDE_SUFFIX) or f.is_symlink())


def shipped_names(files) -> list:
    return sorted(f.relative_to(PKG).as_posix() for f in files if ships(f))


def manifest_listed(manifest_text: str) -> list:
    """The paths listed under "## Files" in MANIFEST.txt (empty when the section is missing)."""
    marker = "\n" + MANIFEST_FILES + "\n"
    if marker not in manifest_text:
        return []
    body = manifest_text.split(marker, 1)[1]
    return [ln[2:] for ln in body.splitlines() if ln.startswith("- ")]


def write_manifest_files(names) -> None:
    path = PKG / "MANIFEST.txt"
    t = path.read_text(encoding="utf-8")
    head = t.split("\n" + MANIFEST_FILES + "\n", 1)[0].rstrip("\n")
    section = (f"\n\n{MANIFEST_FILES}\n(generated by py -I scripts/release/make_release.py --manifest; "
               "every file the release zip ships, under aisec/)\n" + "".join(f"- {n}\n" for n in names))
    path.write_text(head + section, encoding="utf-8", newline="\n")


PLACEHOLDER_FILES = ("README.md", "RELEASE-NOTES-V7.0.md", "RELEASE-NOTES-V7.1.md")


def unfilled_placeholders() -> list:
    """{{NAME}} markers the lead fills at release time (test counts); a release must not ship them."""
    left = []
    for rel in PLACEHOLDER_FILES:
        p = PKG / rel
        if p.exists():
            left += [f"{rel}: {m}" for m in re.findall(r"\{\{[A-Z_]+\}\}", p.read_text(encoding="utf-8"))]
    return left


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--version")
    ap.add_argument("--key", help="path to the release signing private key (ssh-keygen ed25519)")
    ap.add_argument("--manifest", action="store_true", help="rewrite the ## Files list in MANIFEST.txt and stop")
    a = ap.parse_args()
    if a.manifest:
        write_manifest_files(shipped_names(tracked_files()))
        print("MANIFEST.txt file list updated; commit it before building the release")
        return 0
    if not (a.version and a.key):
        ap.error("--version and --key are required to build a release")
    if not re.fullmatch(r"\d+\.\d+\.\d+", a.version):
        sys.exit("version must look like 6.2.1")
    installer = (PKG / "install-global.py").read_text(encoding="utf-8")
    if f'VERSION="{a.version}"' not in installer or f"Version: {a.version}" not in (PKG / "MANIFEST.txt").read_text(encoding="utf-8"):
        sys.exit("bump VERSION in install-global.py and Version in MANIFEST.txt to the release version first")
    left = unfilled_placeholders()
    if left:
        sys.exit("fill the release placeholders first (real numbers from this release's test run): " + ", ".join(left))
    cfg = json.loads((PKG / "config" / "update.json").read_text(encoding="utf-8-sig"))
    signers = (PKG / "config" / "allowed_signers").read_text(encoding="utf-8")
    if signers.startswith("\ufeff"):
        sys.exit("config/allowed_signers starts with a byte order mark (Notepad's 'UTF-8 with BOM'); ssh-keygen then "
                 "misreads the signer name and manual verification fails. Save it as plain UTF-8 and run again.")
    if not cfg.get("repo") or "ssh-ed25519" not in signers:
        sys.exit("config/update.json needs the repo and config/allowed_signers the release public key")
    files = release_files()
    if manifest_listed((PKG / "MANIFEST.txt").read_text(encoding="utf-8")) != shipped_names(files):
        sys.exit("the ## Files list in MANIFEST.txt does not match what this release ships; run "
                 "py -I scripts/release/make_release.py --manifest, commit, and build again")
    out = PKG / "dist"; out.mkdir(exist_ok=True)
    asset = out / cfg["asset"]
    with zipfile.ZipFile(asset, "w", zipfile.ZIP_DEFLATED) as z:
        for f in files:
            if not ships(f):
                continue
            rel = f.relative_to(PKG)
            z.write(f, Path("aisec") / rel)
    sig = Path(str(asset) + ".sig")
    sig.unlink(missing_ok=True)
    keygen = shutil.which("ssh-keygen") or sys.exit("ssh-keygen not found")
    subprocess.run([keygen, "-Y", "sign", "-f", a.key, "-n", "org-appsec-update", str(asset)], check=True)
    with open(asset, "rb") as fh:
        ident = cfg["signer_identity"]
        ok = subprocess.run([keygen, "-Y", "verify", "-f", str(PKG / "config" / "allowed_signers"), "-I", ident,
                             "-n", "org-appsec-update", "-s", str(sig)], stdin=fh).returncode == 0
    if not ok:
        sys.exit("signature does not verify against config/allowed_signers; wrong key?")
    print(f"built and verified {asset.name} + .sig\nnext: gh release create v{a.version} \"{asset}\" \"{sig}\" --repo {cfg['repo']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
