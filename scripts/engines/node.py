"""Node engines: npm audit (part of npm) and eslint-plugin-security (Apache-2.0) on a pinned ESLint (MIT)."""
from __future__ import annotations
import json, os, shutil
from pathlib import Path
from ._base import Engine, NotRunnable, finding, items, load_json, rel

NPM_REGISTRY = "https://registry.npmjs.org/"
LOCKFILES = ("package-lock.json", "npm-shrinkwrap.json")
NPM_SEV = {"critical": "CRITICAL", "high": "HIGH", "moderate": "MEDIUM", "low": "LOW", "info": "INFO"}


class NpmAudit(Engine):
    name, command, languages = "npm-audit", "npm", ("node",)
    needs = ("npm",)
    finds = "known-vulnerable npm packages in package-lock.json"
    timeout = 600

    def argv(self, project, out_dir, ctx):
        npm = ctx.find("npm")
        if not npm:
            raise NotRunnable("npm is not on PATH")
        lock = next((Path(project) / n for n in LOCKFILES if (Path(project) / n).is_file()), None)
        if lock is None or not (Path(project) / "package.json").is_file():
            raise NotRunnable("no package-lock.json (run npm install once to create it)")
        if ctx.mode != "ci":
            return [npm, "audit", "--json"], project, self.timeout, None, None
        # ci: audit a copy of the two files in a private folder, so the repo's .npmrc (registry, proxy,
        # strict-ssl) is never read, and name the registry explicitly.
        work = out_dir / "npm-audit"
        work.mkdir(parents=True, exist_ok=True)
        for src in (Path(project) / "package.json", lock):
            if src.is_symlink() or src.stat().st_size > 50_000_000:
                raise NotRunnable(f"{src.name} is a link or too large to audit")
            shutil.copyfile(src, work / src.name)
        registry = os.environ.get("SECGATE_NPM_REGISTRY", NPM_REGISTRY)
        return [npm, "audit", "--json", "--registry", registry], work, self.timeout, None, None

    def status(self, find=None):
        st = super().status(find) if find else super().status()
        st["pinned"] = "bundled with npm"
        return st

    def exit_ok(self, rc, raw, err):
        try:
            data = load_json(raw)
        except ValueError:
            return False, f"exited {rc} without JSON"
        if not isinstance(data, dict) or data.get("error"):
            msg = (data or {}).get("error", {}) if isinstance(data, dict) else {}
            return False, f"npm audit failed: {str(msg.get('summary', '') if isinstance(msg, dict) else msg)[:200]}"
        return True, "completed"

    def normalize(self, raw, project):
        data = load_json(raw)
        lock = next((n for n in LOCKFILES if (Path(project) / n).is_file()), "package-lock.json")
        out = []
        vulns = data.get("vulnerabilities") if isinstance(data, dict) else None
        for name, v in (vulns.items() if isinstance(vulns, dict) else []):
            if not isinstance(v, dict):
                continue
            adv = [x for x in items(v, "via") if isinstance(x, dict)]
            if not adv:
                continue          # only depends on a vulnerable package; that package has its own entry
            ids = sorted({str(x.get("url", "")).rstrip("/").rsplit("/", 1)[-1] for x in adv if x.get("url")})
            title = adv[0].get("title") or "known vulnerability"
            fix = v.get("fixAvailable")
            fixtxt = "fix available (npm audit fix)" if fix is True else (
                f"fix: {fix.get('name')}@{fix.get('version')}" if isinstance(fix, dict) else "no fix available")
            out.append(finding("npm-audit", ids[0] if ids else f"NPM_AUDIT_{name}",
                               NPM_SEV.get(str(v.get("severity", "")).lower(), "MEDIUM"), lock, 0,
                               f"{name} {v.get('range', '')}: {title}; {fixtxt}", aliases=ids))
        return out


ESLINT_SEV = {"detect-eval-with-expression": "HIGH", "detect-disable-mustache-escape": "HIGH", "detect-bidi-characters": "HIGH",
              "detect-object-injection": "LOW", "detect-non-literal-regexp": "LOW", "detect-possible-timing-attacks": "LOW"}

CONFIG_TEMPLATE = """// Generated by NexaForge SecureCode for one run. The scanned repo's own ESLint config is never loaded.
const security = require(%s);
module.exports = [
  { ignores: ["**/node_modules/**", "**/dist/**", "**/build/**", "**/vendor/**", "**/*.min.js", ".security/**", "coverage/**"] },
  {
    files: ["**/*.js", "**/*.mjs", "**/*.cjs", "**/*.jsx"],
    languageOptions: { ecmaVersion: "latest", sourceType: "module", parserOptions: { ecmaFeatures: { jsx: true } } },
    plugins: { security },
    rules: security.configs.recommended.rules,
  },
  { files: ["**/*.cjs"], languageOptions: { sourceType: "commonjs" } },
];
"""


class EslintSecurity(Engine):
    name, command, languages = "eslint-security", None, ("node",)
    needs = ("node",)
    finds = "JavaScript: eval, child_process, unsafe regex (ReDoS), non-literal fs paths and require, timing attacks"
    version_args = ()

    def eslint_js(self):
        return self.install_dir() / "node_modules" / "eslint" / "bin" / "eslint.js"

    def plugin_dir(self):
        return self.install_dir() / "node_modules" / "eslint-plugin-security"

    def installed_path(self):
        return self.eslint_js()

    def locate(self, find=None):
        p = self.eslint_js()
        return str(p) if p.is_file() and self.plugin_dir().is_dir() else None

    def status(self, find=None):
        st = super().status(find) if find else super().status()
        try:
            st["version"] = json.loads((self.plugin_dir() / "package.json").read_text(encoding="utf-8")).get("version", "")
        except (OSError, ValueError):
            pass
        return st

    def argv(self, project, out_dir, ctx):
        js = self.locate()
        if not js:
            raise NotRunnable("not installed")
        node = ctx.find("node")
        if not node:
            raise NotRunnable("node is not on PATH")
        cfg = out_dir / "nfsc-eslint.config.cjs"
        cfg.write_text(CONFIG_TEMPLATE % json.dumps(str(self.plugin_dir())), encoding="utf-8")
        supp = out_dir / "eslint-suppressions.json"
        supp.write_text("{}", encoding="utf-8")       # a repo eslint-suppressions.json must not hide results
        report = out_dir / "eslint.json"
        cmd = [node, js, "-c", str(cfg), "--suppressions-location", str(supp), "-f", "json", "-o", str(report),
               "--no-error-on-unmatched-pattern"]
        if ctx.mode == "ci":
            cmd.append("--no-inline-config")       # /* eslint-disable */ in the code under review does not count
        return cmd + ["."], project, self.timeout, None, report

    def normalize(self, raw, project):
        data = load_json(raw)
        out = []
        for res in (data if isinstance(data, list) else []):
            if not isinstance(res, dict):
                continue
            for m in items(res, "messages"):
                if not isinstance(m, dict) or m.get("fatal") or not str(m.get("ruleId") or "").startswith("security/"):
                    continue
                rule = str(m["ruleId"]).split("/", 1)[1]
                out.append(finding("eslint-security", f"ESLINT_{m['ruleId']}", ESLINT_SEV.get(rule, "MEDIUM"),
                                   rel(res.get("filePath", ""), project), m.get("line", 0), m.get("message", rule)))
        return out
